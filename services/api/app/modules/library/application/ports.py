from __future__ import annotations

from typing import Protocol

from app.modules.library.domain.model import CourseVersion, LibraryCourse, LibraryResource


class LibraryRepository(Protocol):
    def list_courses(self, *, faculty_domain: str | None = None, program: str | None = None, level: str | None = None, semester: str | None = None, limit: int = 100) -> tuple[LibraryCourse, ...]: ...
    def list_courses_page(self, *, faculty_domain: str | None = None, program: str | None = None, level: str | None = None, semester: str | None = None, query: str | None = None, offset: int = 0, limit: int = 100) -> tuple[LibraryCourse, ...]: ...
    def catalog_revision(self, *, faculty_domain: str | None = None, program: str | None = None, level: str | None = None, semester: str | None = None, query: str | None = None) -> tuple[int, str | None]: ...
    def get_course(self, course_id: str) -> LibraryCourse | None: ...
    def get_version(self, version_id: str) -> CourseVersion | None: ...
    def get_resource(self, resource_id: str) -> LibraryResource | None: ...
    def get_course_for_version(self, version_id: str) -> LibraryCourse | None: ...
    def list_resources(self, version_id: str) -> tuple[LibraryResource, ...]: ...
    def save_course(self, course: LibraryCourse) -> None: ...
    def save_version(self, version: CourseVersion) -> None: ...
    def save_resource(self, resource: LibraryResource) -> None: ...


class LibraryAccessPort(Protocol):
    def is_premium(self, account_id: str) -> bool: ...


class ResourceDeliveryPort(Protocol):
    def create_delivery_token(self, *, account_id: str, resource: LibraryResource, ttl_seconds: int = 300) -> str: ...
    def verify_delivery_token(self, *, account_id: str, resource_id: str, token: str, now_epoch: int | None = None) -> bool: ...
