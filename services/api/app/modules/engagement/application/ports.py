from __future__ import annotations
from typing import Protocol
from ..domain.model import NotificationIntent, NotificationPreferences, EngagementDay

class EngagementRepository(Protocol):
    def get_preferences(self, account_id: str) -> NotificationPreferences: ...
    def save_preferences(self, account_id: str, preferences: NotificationPreferences) -> None: ...
    def list_scheduled_for_day(self, account_id: str, day_key: str) -> tuple[NotificationIntent, ...]: ...
    def save_intent(self, intent: NotificationIntent) -> bool: ...
    def cancel_intent(self, intent_id: str) -> None: ...
    def upsert_day(self, account_id: str, day: EngagementDay) -> None: ...
    def recent_days(self, account_id: str, limit: int = 60) -> tuple[EngagementDay, ...]: ...
    def list_due_push(self, now, limit: int = 100) -> tuple[NotificationIntent, ...]: ...
    def mark_delivered(self, intent_id: str, delivered_at) -> None: ...

class PushRegistry(Protocol):
    def register(self, account_id: str, device_id: str, platform: str, token: str) -> None: ...
    def revoke(self, account_id: str, device_id: str) -> None: ...
    def active_tokens(self, account_id: str) -> tuple[str, ...]: ...
    def revoke_token(self, token: str) -> None: ...

class PushSender(Protocol):
    def send(self, *, tokens: tuple[str, ...], title: str, body: str, deep_link: str) -> tuple[str, ...]: ...
