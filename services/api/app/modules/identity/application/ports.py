from __future__ import annotations

from typing import Protocol

from app.modules.identity.domain.model import Account, RefreshSession, RecoveryChallenge


class AccountRepository(Protocol):
    def get(self, account_id: str) -> Account | None: ...
    def find_by_login(self, login: str) -> Account | None: ...
    def save(self, account: Account) -> None: ...


class SessionRepository(Protocol):
    def get_by_hash(self, token_hash: str) -> RefreshSession | None: ...
    def get(self, session_id: str) -> RefreshSession | None: ...
    def list_for_account(self, account_id: str) -> list[RefreshSession]: ...
    def save(self, session: RefreshSession) -> None: ...
    def revoke(self, account_id: str, session_id: str, now) -> bool: ...
    def revoke_all(self, account_id: str, now=None) -> int: ...


class PasswordHasher(Protocol):
    def hash(self, password: str) -> str: ...
    def verify(self, password_hash: str, password: str) -> bool: ...


class TokenIssuer(Protocol):
    def issue_access(self, account: Account, now) -> tuple[str, int]: ...
    def decode_access(self, token: str) -> dict: ...
    def new_refresh_token(self) -> tuple[str, str]: ...
    def hash_refresh(self, token: str) -> str: ...


class RecoveryChallengeRepository(Protocol):
    def get(self, challenge_id: str) -> RecoveryChallenge | None: ...
    def save(self, challenge: RecoveryChallenge) -> None: ...


class VerificationSender(Protocol):
    enabled: bool
    def send(self, *, destination: str, channel: str, code: str) -> None: ...
