from __future__ import annotations
from typing import Protocol
from app.modules.editorial.domain.model import *

class EditorialRepository(Protocol):
    def get_member(self, account_id:str): ...
    def save_member(self, member:EditorialMember): ...
    def list_members(self): ...
    def get_item(self, item_id:str): ...
    def find_item_by_source_fingerprint(self, fingerprint:str): ...
    def save_item(self, item:EditorialItem, expected_version:int|None=None): ...
    def list_items(self, state=None, limit:int=100): ...
    def search_items(self, **filters): ...
    def get_revision(self, revision_id:str): ...
    def list_revisions(self, item_id:str): ...
    def save_revision(self, revision:EditorialRevision): ...
    def save_review(self, review:ReviewDecision): ...
    def list_reviews(self, item_id:str): ...
    def save_publication(self, record:PublicationRecord): ...
    def list_publications(self, item_id:str): ...
    def save_source(self, source:EditorialSource): ...
    def list_sources(self, item_id:str): ...
    def get_source(self, source_id:str): ...
    def find_source_by_checksum(self, checksum:str): ...
    def save_assignment(self, assignment:EditorialAssignment): ...
    def list_assignments(self, item_id:str|None=None, assignee_id:str|None=None, active_only:bool=False): ...
    def get_active_assignment(self, item_id:str, stage:AssignmentStage): ...
    def complete_assignment(self, item_id:str, stage:AssignmentStage): ...

class PublicationProjector(Protocol):
    def project(self, *, item:EditorialItem, revision:EditorialRevision, changelog:str, published_at): ...
    def archive(self, *, item:EditorialItem, archived_at): ...
