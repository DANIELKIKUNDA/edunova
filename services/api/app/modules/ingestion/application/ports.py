from __future__ import annotations

from typing import Protocol
from datetime import datetime
from pathlib import Path

from ..domain.model import IngestionBatch, IngestionDocument, IngestionJob, IngestionResult


class IngestionRepository(Protocol):
    def save_batch(self, batch: IngestionBatch) -> None: ...
    def get_batch(self, batch_id: str) -> IngestionBatch | None: ...
    def list_batches(self, *, limit: int = 50, offset: int = 0) -> tuple[IngestionBatch, ...]: ...
    def save_document(self, document: IngestionDocument) -> None: ...
    def get_document(self, document_id: str) -> IngestionDocument | None: ...
    def list_documents(self, batch_id: str) -> tuple[IngestionDocument, ...]: ...
    def find_document_by_idempotency(self, batch_id: str, key: str) -> IngestionDocument | None: ...
    def find_document_by_checksum(self, batch_id: str, checksum: str) -> IngestionDocument | None: ...
    def find_successful_document_by_checksum(self, checksum: str) -> IngestionDocument | None: ...
    def save_job(self, job: IngestionJob) -> None: ...
    def get_job(self, job_id: str) -> IngestionJob | None: ...
    def list_jobs(self, batch_id: str) -> tuple[IngestionJob, ...]: ...
    def claim_next_job(self, *, worker_id: str, now: datetime, lease_seconds: int) -> IngestionJob | None: ...
    def heartbeat(self, *, job_id: str, worker_id: str, now: datetime, lease_seconds: int) -> bool: ...
    def recover_expired_leases(self, *, now: datetime) -> int: ...
    def save_result(self, result: IngestionResult) -> None: ...
    def get_result_for_document(self, document_id: str) -> IngestionResult | None: ...
    def list_results(self, batch_id: str) -> tuple[IngestionResult, ...]: ...


class StagingStorage(Protocol):
    def put(self, key: str, payload: bytes, *, content_type: str) -> None: ...
    def read(self, key: str) -> bytes: ...
    def delete(self, key: str) -> None: ...
    def put_text(self, key: str, payload: str, *, content_type: str = "application/json") -> None: ...


class MalwareScanner(Protocol):
    def scan(self, payload: bytes, *, filename: str) -> None: ...


class EditorialBridge(Protocol):
    def create_from_processed_document(self, *, actor_id: str, batch: IngestionBatch, document: IngestionDocument, processed, artifact_key: str) -> str: ...
